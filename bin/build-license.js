#!/usr/bin/env node
/**
 * Regenerates the third-party section of license.txt.
 *
 * WordPress keeps third-party notices in license.txt below a marker. Only that
 * section is generated; the GPL text above it is edited by hand. Notices come
 * from the webpack module list so transitive bundled dependencies are included.
 *
 * Run with `npm run licenses` after changing dependencies.
 */
const { execFileSync } = require( 'child_process' );
const fs = require( 'fs' );
const path = require( 'path' );

const ROOT = path.resolve( __dirname, '..' );
const MODULES = path.join( ROOT, 'node_modules' );
const LICENSE = path.join( ROOT, 'license.txt' );

const MARKER =
	'This program incorporates work covered by the following copyright and\npermission notices:';

// Licenses that waive the notice requirement and need no full text.
const NO_NOTICE_REQUIRED = [ '0BSD', 'CC0-1.0', 'Unlicense' ];

function bundledPackages() {
	const stats = execFileSync(
		'npx',
		[ 'webpack', '--config', 'webpack.config.js', '--json' ],
		{ cwd: ROOT, env: { ...process.env, NODE_ENV: 'production' }, maxBuffer: 256 * 1024 * 1024 }
	).toString();

	const found = new Set();
	for ( const mod of JSON.parse( stats ).modules || [] ) {
		const match = /node_modules\/((?:@[^/]+\/)?[^/]+)/.exec( mod.name || '' );
		if ( match ) {
			found.add( match[ 1 ] );
		}
	}
	return [ ...found ].sort();
}

function licenceText( pkgDir ) {
	const names = fs.readdirSync( pkgDir ).filter( ( f ) => /^(LICENSE|LICENCE|COPYING)/i.test( f ) );
	return names.length ? fs.readFileSync( path.join( pkgDir, names[ 0 ] ), 'utf8' ).trim() : null;
}

/**
 * Reconstructs the MIT notice for packages that declare an MIT license but do
 * not include a license file.
 *
 * @param {Object} meta Parsed package.json.
 * @return {string|null} Licence text, or null when the author is unknown.
 */
function mitFallback( meta ) {
	if ( 'MIT' !== meta.license ) {
		return null;
	}
	const author = typeof meta.author === 'string' ? meta.author : meta.author && meta.author.name;
	if ( ! author ) {
		return null;
	}

	return `MIT License

Copyright (c) ${ author }

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.

(Reconstructed from the MIT declaration in package.json; this package ships no
licence file of its own.)`;
}

const sections = [];
const missing = [];

for ( const name of bundledPackages() ) {
	const dir = path.join( MODULES, name );
	let meta;
	try {
		meta = JSON.parse( fs.readFileSync( path.join( dir, 'package.json' ), 'utf8' ) );
	} catch ( e ) {
		continue;
	}

	// GPL-compatible and already covered by the plugin's own licence above.
	if ( String( meta.license || '' ).startsWith( 'GPL-2.0' ) ) {
		continue;
	}

	const header = `${ meta.name } ${ meta.version }\nLicence: ${ meta.license || 'see below' }` +
		( meta.homepage ? `\nHomepage: ${ meta.homepage }` : '' );

	if ( NO_NOTICE_REQUIRED.includes( meta.license ) ) {
		sections.push( `${ header }\n(This licence does not require the notice to be reproduced.)` );
		continue;
	}

	const text = licenceText( dir ) || mitFallback( meta );
	if ( ! text ) {
		missing.push( `${ meta.name }@${ meta.version } (${ meta.license })` );
		continue;
	}
	sections.push( `${ header }\n\n${ text }` );
}

const existing = fs.readFileSync( LICENSE, 'utf8' );
const cut = existing.indexOf( MARKER );
if ( -1 === cut ) {
	process.stderr.write( `Marker not found in license.txt; refusing to overwrite.\n` );
	process.exit( 1 );
}

const preamble = `${ MARKER }

Gitwire's admin bundle (build/index.js) compiles in the libraries below, each
under its own licence and all compatible with the GPL. WordPress packages
loaded from core at runtime are not listed, and neither are packages already
licensed GPL-2.0-or-later, which this program's own licence covers.

Generated by \`npm run licenses\` from the webpack module list. Do not edit by
hand; edits below this point are overwritten.
`;

const divider = `\n\n${ '-'.repeat( 78 ) }\n\n`;
fs.writeFileSync( LICENSE, `${ existing.slice( 0, cut ) }${ preamble }${ divider }${ sections.join( divider ) }\n` );

process.stdout.write( `Wrote license.txt covering ${ sections.length } bundled packages.\n` );
if ( missing.length ) {
	process.stdout.write( `\nNo licence file found, add by hand:\n  ${ missing.join( '\n  ' ) }\n` );
	process.exitCode = 1;
}
